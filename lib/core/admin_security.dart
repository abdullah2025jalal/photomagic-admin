import 'dart:convert';
import 'dart:math';
import 'dart:typed_data';

import 'package:crypto/crypto.dart';

/// Security primitives shared with the aligner app (same schema contract).
///
/// * ACCOUNT PASSWORDS: PBKDF2-HMAC-SHA256 v2, wire format
///   `v2$100000$salt$digest` — IDENTICAL to the aligner app's
///   `PasswordHasher`. Legacy bare-sha256 accounts are still verified
///   (see [verifyAccount]) so nothing breaks on upgrade.
/// * MASTER PASSWORD: verified against a compiled PBKDF2 constant
///   (60,000 iterations). A single SHA-256 constant could be brute-forced
///   at billions of guesses/sec from a decompile; PBKDF2 makes each guess
///   60,000x more expensive, and the gate adds a forced 3 s delay per
///   attempt on top (see master_gate_screen).
/// * STORED PLAIN PASSWORDS (`pass` field in the cloud): encrypted at rest
///   with a key derived from the master password (encrypt-then-MAC,
///   tamper-evident). A stolen database without the master password no
///   longer leaks every customer's plain password.
class AdminSecurity {
  AdminSecurity._();

  // ---------------------------------------------------------------------
  // Master password verification (compiled PBKDF2 constant).
  // ---------------------------------------------------------------------

  /// Legacy salt of the ORIGINAL single-sha256 constant (kept only so
  /// [legacyVerifyMaster] still validates the constant's provenance).
  static const String masterSalt = 'n5_admin_2026_static_salt_v1';

  /// PBKDF2-HMAC-SHA256, 60,000 iterations, salt
  /// `n5_admin_master_kdf_v2`, over the owner's master password.
  /// Generated by `dart run tool/compute_master_hash.dart`.
  static const String masterHashV2 =
      'v2\$60000\$n5_admin_master_kdf_v2\$'
      '81a1b4ea864427ea748fe904bebf652312cd75ddae698e652c94e66bc216de13';

  /// True when [password] matches the owner's master password.
  /// Slowed deliberately: PBKDF2 60k (~60 ms) + the gate's own 3 s delay.
  static bool verifyMaster(String password) {
    final List<String> parts = masterHashV2.split('\$');
    if (parts.length != 4) return false;
    final int? iter = int.tryParse(parts[1]);
    if (iter == null || iter < 1) return false;
    final String candidate =
        _hex(pbkdf2Bytes(password, parts[2], iterations: iter));
    return fixedTimeEquals(candidate, parts[3]);
  }

  /// Key derivation for the at-rest encryption of stored plain passwords.
  /// Fixed device salt: the ciphertext is bound to THIS app install.
  static const String _kdfSalt = 'n5_admin_atrest_kdf_v1';

  /// Derives the 32-byte at-rest key from the master password.
  static Uint8List deriveAtRestKey(String masterPassword) =>
      pbkdf2Bytes(masterPassword, _kdfSalt, iterations: 60000);

  /// The at-rest key for THIS unlock session, set by the gate screen right
  /// after a successful [verifyMaster]. Never persisted — it exists only in
  /// RAM while the panel is open; process death loses it (re-derived at the
  /// next unlock, which happens on EVERY launch by design).
  static Uint8List? sessionKey;

  /// True when [value] is an enc1$… at-rest blob (vs legacy plaintext).
  static bool isEncryptedAtRest(String value) =>
      value.startsWith('enc1\$');

  // ---------------------------------------------------------------------
  // PBKDF2-HMAC-SHA256 core (RFC 2898 §5.2) over package:crypto.
  // ---------------------------------------------------------------------

  static Uint8List pbkdf2Bytes(
    String password,
    String salt, {
    required int iterations,
    int keyLen = 32,
  }) {
    final List<int> pw = utf8.encode(password);
    final List<int> sl = utf8.encode(salt);
    final Hmac hmac = Hmac(sha256, pw);
    final int blocks = (keyLen + 31) ~/ 32;
    final Uint8List out = Uint8List(keyLen);
    for (int block = 1; block <= blocks; block++) {
      final BytesBuilder bb = BytesBuilder();
      bb.add(sl);
      bb.add(<int>[
        (block >>> 24) & 0xff,
        (block >>> 16) & 0xff,
        (block >>> 8) & 0xff,
        block & 0xff,
      ]);
      Uint8List u = Uint8List.fromList(hmac.convert(bb.toBytes()).bytes);
      final Uint8List t = Uint8List.fromList(u);
      for (int i = 1; i < iterations; i++) {
        u = Uint8List.fromList(hmac.convert(u).bytes);
        for (int j = 0; j < t.length; j++) {
          t[j] ^= u[j];
        }
      }
      final int offset = (block - 1) * 32;
      final int take = min(32, keyLen - offset);
      out.setRange(offset, offset + take, t);
    }
    return out;
  }

  // ---------------------------------------------------------------------
  // Account password hashing (v2 = aligner app contract).
  // ---------------------------------------------------------------------

  /// v2 PBKDF2 hash for a NEW account password.
  static String hash(String salt, String password) =>
      'v2\$100000\$$salt\$${_hex(pbkdf2Bytes(password, salt, iterations: 100000))}';

  /// LEGACY v1: `sha256(salt+password)` — only for pre-upgrade accounts.
  static String legacyHash(String salt, String password) =>
      sha256.convert(utf8.encode('$salt$password')).toString();

  /// Verifies [password] against [stored], accepting both formats.
  /// Returns the v2 hash to persist when a legacy account authenticated
  /// (transparent upgrade), null otherwise.
  static ({bool ok, String? upgraded}) verifyAccount(
    String salt,
    String password,
    String stored,
  ) {
    if (stored.startsWith('v2\$')) {
      final List<String> parts = stored.split('\$');
      if (parts.length != 4) return (ok: false, upgraded: null);
      final int? iter = int.tryParse(parts[1]);
      final String digest = parts[3];
      if (iter == null || iter < 1 || digest.length != 64) {
        return (ok: false, upgraded: null);
      }
      final String candidate =
          _hex(pbkdf2Bytes(password, parts[2], iterations: iter));
      return (ok: fixedTimeEquals(candidate, digest), upgraded: null);
    }
    if (stored.length != 64) return (ok: false, upgraded: null);
    final bool ok = fixedTimeEquals(legacyHash(salt, password), stored);
    return (
      ok: ok,
      upgraded: ok ? hash(salt, password) : null,
    );
  }

  // ---------------------------------------------------------------------
  // At-rest encryption of stored plain passwords (encrypt-then-MAC).
  // Keystream: HMAC-SHA256(key, nonce || blockIndex) in 32-byte blocks.
  // ---------------------------------------------------------------------

  /// Encrypts [plain] into `enc1$nonce$ct$tag` under [key].
  static String encryptAtRest(String plain, Uint8List key) {
    final Random r = Random.secure();
    final Uint8List nonce = Uint8List(16);
    for (int i = 0; i < nonce.length; i++) {
      nonce[i] = r.nextInt(256);
    }
    final Uint8List data = Uint8List.fromList(utf8.encode(plain));
    final Uint8List ct = _ctrXor(data, key, nonce);
    final Hmac mac = Hmac(sha256, key);
    final String tag = _hex(mac.convert(<int>[...nonce, ...ct]).bytes);
    return 'enc1\$${_hex(nonce)}\$${_hex(ct)}\$$tag';
  }

  /// Reverses [encryptAtRest]; null on tamper or wrong key.
  static String? decryptAtRest(String blob, Uint8List key) {
    final List<String> parts = blob.split('\$');
    if (parts.length != 4 || parts[0] != 'enc1') return null;
    final Uint8List nonce = _unhex(parts[1]);
    final Uint8List ct = _unhex(parts[2]);
    final Uint8List tag = _unhex(parts[3]);
    if (nonce.length != 16) return null;
    final Hmac mac = Hmac(sha256, key);
    final String expect = _hex(mac.convert(<int>[...nonce, ...ct]).bytes);
    if (!fixedTimeEquals(expect, _hex(tag))) return null;
    try {
      return utf8.decode(_ctrXor(ct, key, nonce));
    } catch (_) {
      return null;
    }
  }

  static Uint8List _ctrXor(Uint8List data, Uint8List key, Uint8List nonce) {
    final Hmac hmac = Hmac(sha256, key);
    final Uint8List out = Uint8List(data.length);
    Uint8List? block;
    int blockIndex = -1;
    for (int i = 0; i < data.length; i++) {
      final int b = i ~/ 32;
      if (b != blockIndex) {
        final BytesBuilder bb = BytesBuilder();
        bb.add(nonce);
        bb.add(<int>[b & 0xff]);
        block = Uint8List.fromList(hmac.convert(bb.toBytes()).bytes);
        blockIndex = b;
      }
      out[i] = data[i] ^ block![i % 32];
    }
    return out;
  }

  static String _hex(List<int> bytes) =>
      bytes.map((int b) => b.toRadixString(16).padLeft(2, '0')).join();

  static Uint8List _unhex(String s) {
    final Uint8List out = Uint8List(s.length ~/ 2);
    for (int i = 0; i < out.length; i++) {
      out[i] = int.parse(s.substring(i * 2, i * 2 + 2), radix: 16);
    }
    return out;
  }

  /// Length-independent constant-time comparison.
  static bool fixedTimeEquals(String a, String b) {
    if (a.length != b.length) return false;
    int diff = 0;
    for (int i = 0; i < a.length; i++) {
      diff |= a.codeUnitAt(i) ^ b.codeUnitAt(i);
    }
    return diff == 0;
  }

  // ---------------------------------------------------------------------
  // Generators (identical contract to the aligner app).
  // ---------------------------------------------------------------------

  /// Random 128-bit hex salt for new customer accounts.
  static String newSalt([Random? rng]) {
    final Random r = rng ?? Random.secure();
    final StringBuffer sb = StringBuffer();
    for (int i = 0; i < 32; i++) {
      sb.write('0123456789abcdef'[r.nextInt(16)]);
    }
    return sb.toString();
  }

  /// Unambiguous random password (no 0/O/1/l/I) for new customers.
  /// 10 chars (~58 bits) — with v2 slow hashing, beyond practical guessing.
  static String newPassword([Random? rng]) {
    const String alphabet =
        'ABCDEFGHJKLMNPQRSTUVWXYZabcdefghjkmnpqrstuvwxyz23456789';
    final Random r = rng ?? Random.secure();
    final StringBuffer sb = StringBuffer();
    for (int i = 0; i < 10; i++) {
      sb.write(alphabet[r.nextInt(alphabet.length)]);
    }
    return sb.toString();
  }
}
